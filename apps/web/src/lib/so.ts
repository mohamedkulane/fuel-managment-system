const normalizedLabels = new Map(Object.entries(labels).map(([label, translation]) => [label.toLowerCase(), translation]));

export function so(text: string): string {
  return labels[text] ?? normalizedLabels.get(text.toLowerCase()) ?? text;
}

export function soError(message: string, status: number): string {
  if (/^Debt is \$\d{1,14}\.\d{2}\. You cannot pay more\.$/.test(message)) {
    const amount = message.match(/\$[\d,.]+/)?.[0] ?? "";
    return `Deyntu waa ${amount}. Lacag intaas ka badan lama bixin karo.`;
  }
  const exact = labels[message];
  if (exact) return exact;
  if (/balance is too low/i.test(message)) return "Hadhaaga akoonku kuma filna lacag-bixintan (Akoonku ma ogola hadhaa taban). Haddii aad shidaalkan deyn ku qaadatay, 'Hadda la bixiyey' ka dhig 0 si wadarta oo dhami deyn ugu noqoto keenaha.";
  if (/negative-balance policy/i.test(message)) return "Milkiiluhu waa inuu marka hore doortaa siyaasadda hadhaaga taban ee akoonkan.";
  if (/cannot exceed the purchase total/i.test(message)) return "Lacagta hadda la bixiyey kama badnaan karto wadarta soo-iibsiga.";
  if (/supplier is required/i.test(message)) return "Keenaha shidaalka waa qasab marka kharash la gelinayo.";
  if (/insufficient|not enough stock/i.test(message)) return labels["Not enough stock"]!;
  if (/price changed/i.test(message)) return labels["Price changed. Review the order."]!;
  if (/network|failed to fetch|fetch failed/i.test(message)) return labels["Connection problem. Try again."]!;
  if (/unauthorized|forbidden|permission/i.test(message)) return labels["Permission denied"]!;
  if (/not found/i.test(message)) return "Xogta la codsaday lama helin.";
  if (/already (?:reversed|processed)|duplicate/i.test(message)) return labels["Already processed"]!;
  if (status === 401) return labels["Session expired"]!;
  if (status === 403) return labels["Permission denied"]!;
  if (status >= 500) return labels["Something went wrong"]!;
  return status >= 400 ? "Codsiga lama aqbalin. Hubi xogta oo mar kale isku day." : labels["Request failed"]!;
}
